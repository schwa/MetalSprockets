import Metal
import MetalSprockets
import MetalSprocketsSupport
import simd

// Element is like SwiftUI View but for Metal
struct DemoCubeRenderPipeline: Element {
    let shaderLibrary: ShaderLibrary
    let transforms: [float4x4]
    let time: Float
    let instanced: Bool

    init(transform: float4x4, time: Float) throws {
        try self.init(transforms: [transform], time: time)
    }

    /// Draws one cube per transform: either one instanced draw, or one draw per cube (`ForEach`) to stress per-draw cost.
    init(transforms: [float4x4], time: Float, instanced: Bool = false) throws {
        // ShaderLibrary generated by @ShaderLibrary macro - type-safe access to .metal shaders
        self.shaderLibrary = try ShaderLibrary(bundle: .main)
        self.transforms = transforms
        self.time = time
        self.instanced = instanced
    }

    var body: some Element {
        get throws {
            let vertices = generateCubeVertices()
            if instanced {
                try RenderPipeline(label: "Instanced Cubes", vertexShader: shaderLibrary.vertexInstanced, fragmentShader: shaderLibrary.fragmentMain) {
                    Draw { [instanceCount = transforms.count] encoder in
                        encoder.drawPrimitives(primitiveType: .triangle, vertexStart: 0, vertexCount: cubeVertexCount, instanceCount: instanceCount)
                    }
                    .vertexValues(vertices, index: 0)
                    .parameter("transforms", values: transforms)
                    .parameter("time", value: time)
                }
                .vertexDescriptor(Vertex.descriptor)
                .depthCompare(function: .less, enabled: true)
            } else {
                // RenderPipeline binds shaders and configures pipeline state
                try RenderPipeline(label: "Vertex-Colored Cube", vertexShader: shaderLibrary.vertexMain, fragmentShader: shaderLibrary.fragmentMain) {
                    ForEach(Array(transforms.enumerated()), id: \.offset) { _, transform in
                        // Draw gives direct access to the Metal 4 render encoder; the pipeline and inputs are already bound.
                        Draw { encoder in
                            encoder.drawPrimitives(primitiveType: .triangle, vertexStart: 0, vertexCount: cubeVertexCount)
                        }
                        // Metal 4 has no setVertexBytes: small vertex data goes through scratch storage.
                        .vertexValues(vertices, index: 0)
                        // Bind shader uniforms by name via reflection — no hardcoded buffer indices.
                        .parameter("transform", value: transform)
                        .parameter("time", value: time)
                    }
                }
                // Tells Metal how to interpret Vertex struct
                .vertexDescriptor(Vertex.descriptor)
                .depthCompare(function: .less, enabled: true)
            }
        }
    }
}
